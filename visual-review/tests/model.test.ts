import { expect, test } from 'claude-code/testing'

import type { Host } from '../hooks/host'
import { checkModel, checkRanges, narrowModel, RANGE_NAME_LINES, rangeGap } from '../hooks/model'
import type { DesignModel, Unit } from '../hooks/model'

const RUN = 'vr-1'
const ROOT = 'C:/work/shop'
const BASE = '540a818'

const CART_CS = ['namespace Shop.Orders;', '', '[Table("carts")]', 'public sealed class Cart', '{', '  public int Id { get; set; }', '}'].join('\r\n')

/** A full non-context unit of `file`, with its range on lines 3-7 of CART_CS. */
const unit = (id: string, file: string, extra: Partial<Unit> = {}): Unit => ({
  id,
  name: 'Cart',
  kind: 'class',
  state: 'added',
  file,
  container: 'Shop.Orders',
  range: { start: 3, end: 7 },
  methods: 0,
  members: [],
  summary: 'Holds the items of an order.',
  cohesion: { score: 5, reason: 'One responsibility.' },
  ...extra,
})

const model = (extra: Partial<DesignModel>): DesignModel => ({ runId: RUN, units: [], relations: [], tables: [], skippedFiles: [], ...extra })

test('TC-05 FR-06 a model that leaves out a changed .cs, .ts or .py file gets a gap that names each file', () => {
  const changed = ['src/Cart.cs', 'web/cart.ts', 'api/cart.py', 'README.md']

  const gaps = checkModel(model({}), changed)

  expect(gaps).toEqual([
    'src/Cart.cs: the changed file is not covered; add its units, the table it changes, or a skippedFiles entry',
    'web/cart.ts: the changed file is not covered; add its units, the table it changes, or a skippedFiles entry',
    'api/cart.py: the changed file is not covered; add its units, the table it changes, or a skippedFiles entry',
  ])
})

test('TC-05 a unit, a table source and a skippedFiles entry each cover their file', () => {
  const changed = ['src/Cart.cs', 'db/Migrations/001_Carts.cs', 'db/Migrations/001_Carts.Designer.cs']
  const covering = model({
    units: [unit('Shop.Orders.Cart', 'src/Cart.cs')],
    tables: [{ id: 'carts', state: 'added', source: 'db/Migrations/001_Carts.cs', entity: 'Shop.Orders.Cart', columns: [] }],
    skippedFiles: [{ file: 'db/Migrations/001_Carts.Designer.cs', reason: 'Generated by EF Core.' }],
  })

  expect(checkModel(covering, changed)).toEqual([])
})

test('TC-05 a relation or a table entity that names an unknown unit is a gap', () => {
  const broken = model({
    units: [unit('Shop.Orders.Cart', 'src/Cart.cs')],
    relations: [{ from: 'Shop.Orders.Cart', to: 'Shop.Orders.Item', kind: 'composition', state: 'added' }],
    tables: [{ id: 'carts', state: 'added', source: 'src/Cart.cs', entity: 'Shop.Cart', columns: [] }],
  })

  expect(checkModel(broken, ['src/Cart.cs'])).toEqual([
    'carts: the entity Shop.Cart is not a unit of the model',
    'Shop.Orders.Cart → Shop.Orders.Item: Shop.Orders.Item is not a unit of the model',
  ])
})

test('FR-06 a context unit needs only its identity, and a modified unit without baseRange is a problem', () => {
  const input = {
    runId: RUN,
    units: [
      { id: 'Shop.Orders.Item', name: 'Item', kind: 'class', state: 'context', file: './src\\Item.cs', container: 'Shop.Orders' },
      { ...unit('Shop.Orders.Cart', 'src/Cart.cs'), state: 'modified' },
    ],
    relations: [],
    tables: [],
  }

  const narrowed = narrowModel(input)

  expect(narrowed.value.units[0]).toEqual({ id: 'Shop.Orders.Item', name: 'Item', kind: 'class', state: 'context', file: 'src/Item.cs', container: 'Shop.Orders', members: [] })
  expect(narrowed.problems).toEqual(['units[1] (Shop.Orders.Cart): a modified unit needs baseRange, its lines in the base file'])
})

