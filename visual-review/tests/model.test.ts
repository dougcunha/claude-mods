/** 10 lines with the class name on line 6, after attribute lines. */
const LONG_CS = ['namespace Shop.Orders;', '', '[Table("carts")]', '[Index(nameof(Id))]', '[Owned]', 'public sealed class Cart', '{', '  public int Id { get; set; }', '}', ''].join('\r\n')

const RANGE_CASES = [
  ['starts on the name line', { start: 6, end: 9 }, null],
  [`has the name on its line ${RANGE_NAME_LINES}`, { start: 2, end: 9 }, null],
  [`has the name on its line ${RANGE_NAME_LINES + 1}`, { start: 1, end: 9 }, 'src/Cart.cs does not show the name Cart in its first 5 lines'],
  ['ends on the last line', { start: 6, end: 10 }, null],
  ['ends after the last line', { start: 6, end: 11 }, 'src/Cart.cs ends after the last line (10)'],
] as const

for (const [name, range, expected] of RANGE_CASES) {
  test(`DEC-08 a range that ${name}`, () => {
    const gap = rangeGap(unit('Shop.Orders.Cart', 'src/Cart.cs'), { range, text: LONG_CS, side: 'current' })

    expect(gap === null ? null : gap.slice(gap.indexOf('src/'))).toBe(expected)
  })
}

test('DEC-08 a deleted unit is checked in the base file, and a file that cannot be read leaves its unit unchecked', async () => {
  const ran: string[][] = []
  const host = {
    run: async (argv: string[]) => (ran.push(argv), { exitCode: 0, stdout: CART_CS }),
    readFile: async () => {
      throw new Error('over 4 MiB')
    },
  } as unknown as Host
  const units = [unit('Shop.Orders.Cart', 'src/Cart.cs', { state: 'deleted' }), unit('Shop.Big', 'src/Big.cs')]

  const result = await checkRanges(host, { root: ROOT, base: BASE }, units)

  expect(result).toEqual({ gaps: [], unchecked: ['Shop.Big'] })
  expect(ran).toEqual([['git', 'show', `${BASE}:src/Cart.cs`]])
})

/** A host whose current files hold CART_CS and whose base commit holds only `src/OldCart.cs` (LONG_CS), or cuts its output. */
function renameHost({ isCut = false } = {}): { host: Host; ran: string[][] } {
  const ran: string[][] = []
  const host = {
    run: async (argv: string[]) => {
      ran.push(argv)
      if (isCut) return { exitCode: 0, stdout: '', isStdoutTruncated: true }

      return argv[2] === `${BASE}:src/OldCart.cs` ? { exitCode: 0, stdout: LONG_CS } : { exitCode: 128, stdout: '' }
    },
    readFile: async () => CART_CS,
  } as unknown as Host

  return { host, ran }
}

const RENAMES = new Map([['src/Cart.cs', 'src/OldCart.cs']])

test('DEC-08 the base range of a renamed file is checked at its old path, and a wrong one is a gap', async () => {
  const { host, ran } = renameHost()
  const good = unit('Shop.Orders.Cart', 'src/Cart.cs', { state: 'modified', baseRange: { start: 6, end: 9 } })
  const wrong = unit('Shop.Orders.Cart', 'src/Cart.cs', { state: 'modified', baseRange: { start: 1, end: 9 } })

  expect(await checkRanges(host, { root: ROOT, base: BASE, oldPaths: RENAMES }, [good])).toEqual({ gaps: [], unchecked: [] })
  const result = await checkRanges(host, { root: ROOT, base: BASE, oldPaths: RENAMES }, [wrong])

  expect(result.gaps).toEqual([expect.stringContaining('baseRange 1-9 in the base file src/Cart.cs does not show the name Cart')])
  expect(ran.every(argv => argv[2] === `${BASE}:src/OldCart.cs`)).toBe(true)
})

test('DEC-08 a modified unit whose file is not in the base commit is a gap, and a base file Git cuts leaves it unchecked', async () => {
  const modified = unit('Shop.Orders.Cart', 'src/Cart.cs', { state: 'modified', baseRange: { start: 6, end: 9 } })

  const missing = await checkRanges(renameHost().host, { root: ROOT, base: BASE }, [modified])
  const cut = await checkRanges(renameHost({ isCut: true }).host, { root: ROOT, base: BASE }, [modified])

  expect(missing).toEqual({ gaps: ['Shop.Orders.Cart: the base file src/Cart.cs is not in the base commit; use the state added for a unit of a new file'], unchecked: [] })
  expect(cut).toEqual({ gaps: [], unchecked: ['Shop.Orders.Cart'] })
})
