test('NFR-04 two builds of the same model and diff give the same view model, and a cut diff leaves every unit delta unknown', () => {
  const cut = buildView({ run: RUN, model: CSHARP.model, files: CSHARP.files, hunks: { files: CSHARP.hunks, isTruncated: true }, unchecked: ['Shop.Orders.Cart'] })

  expect(JSON.stringify(view(CSHARP))).toBe(JSON.stringify(view(CSHARP)))
  expect(cut.units.filter(one => one.state !== 'context').map(one => one.added)).toEqual([null, null, null])
  expect(cut.units.find(one => one.id === 'Shop.Orders.Cart')?.isRangeChecked).toBe(false)
})

