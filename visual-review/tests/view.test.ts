const view = (fixture: Fixture): ViewModel => buildView({ run: RUN, model: fixture.model, files: fixture.files, hunks: { files: fixture.hunks, isTruncated: false }, unchecked: [] })

const EXPECTED = [
  [CSHARP, { states: ['context', 'added', 'deleted', 'modified'], tables: ['carts', 'orders'], links: 2, otherFiles: ['README.md', 'src/Data/Migrations/20261022_AddCarts.Designer.cs'] }],
  [TYPESCRIPT, { states: ['modified', 'added'], tables: ['Cart'], links: 0, otherFiles: [] }],
  [PYTHON, { states: ['modified'], tables: ['orders'], links: 1, otherFiles: [] }],
] as const

for (const [fixture, expected] of EXPECTED) {
  test(`TC-09 FR-07 to FR-16 the view model of ${fixture.name} has the states, full cards, the table layer, entity links and other files`, () => {
    const result = view(fixture)

    expect(result.units.map(one => one.state)).toEqual([...expected.states])
    for (const card of result.units.filter(one => one.state !== 'context'))
      expect([card.lines, card.added, card.removed, card.methods, card.summary, card.cohesion].includes(null)).toBe(false)
    expect(result.tables.map(table => table.id)).toEqual([...expected.tables])
    expect(result.links).toHaveLength(expected.links)
    expect(result.otherFiles.map(file => file.path)).toEqual([...expected.otherFiles])
  })
}

test('TC-09 a C# card carries Git deltas, Ce and Ca from live relations only, and the toolbar counts', () => {
  const result = view(CSHARP)
  const card = (id: string) => result.units.find(one => one.id === id)

  expect(card('Shop.Orders.Order')).toMatchObject({ lines: 26, added: 3, removed: 1, ce: 0, ca: 0 })
  expect(card('Shop.Orders.LegacyBasket')).toMatchObject({ added: 0, removed: 12 })
  expect(card('Shop.Orders.Cart')).toMatchObject({ added: 18, removed: 0, ce: 1 })
  expect(card('Shop.Catalog.Product')).toMatchObject({ ca: 1, lines: null, added: null })
  expect(result.files.find(file => file.path === 'src/Orders/Cart.cs')?.rest).toEqual({ added: 2, removed: 0 })
  expect(result.links).toEqual([
    { id: 'Shop.Orders.Cart⇢carts', unit: 'Shop.Orders.Cart', table: 'carts' },
    { id: 'Shop.Orders.Order⇢orders', unit: 'Shop.Orders.Order', table: 'orders' },
  ])
  expect(result.counts).toEqual({ units: { added: 1, modified: 1, deleted: 1 }, tables: { added: 1, modified: 1, dropped: 0 } })
})

test('FR-23 the view model lists each anchor once as <kind>:<id>, in text order, for the static page', () => {
  const result = view(CSHARP)
  const count = result.units.length + result.units.flatMap(unit => unit.members).length + result.relations.length + result.tables.length + result.tables.flatMap(table => table.columns).length

  expect(result.anchors).toEqual(expect.arrayContaining(['unit:Shop.Orders.Cart', 'table:carts', `relation:${result.relations[0]?.id}`]))
  expect(result.anchors).toHaveLength(count)
  expect(result.anchors).toEqual([...result.anchors].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)))
})

