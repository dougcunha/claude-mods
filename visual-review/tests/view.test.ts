test('TC-06 writeView reads Git again and writes view.json in the session folder', async () => {
  const written: [string, string][] = []
  const host = {
    run: async (argv: string[]) => {
      const command = argv.join(' ')
      if (command === 'git diff --numstat -z -M 540a818') return { exitCode: 0, stdout: '3\t1\tshop/models.py\x00' }
      if (command === 'git -c core.quotePath=false diff -U0 --no-color -M --src-prefix=a/ --dst-prefix=b/ 540a818')
        return { exitCode: 0, stdout: ['--- a/shop/models.py', '+++ b/shop/models.py', '@@ -12 +12,3 @@', '-total = Column(Integer)', '+total = Column(', '+    Numeric(10, 2),', '+)', ''].join('\n') }

      return { exitCode: 0, stdout: '' }
    },
    env: async () => ({ temp: 'C:\\Temp' }),
    sessionId: async () => 's-1',
    storeGet: async () => undefined,
    writeFile: async (path: string, text: string) => void written.push([path, text]),
  } as unknown as Host

  const result = await writeView(host, { run: { ...RUN, root: 'C:/work/shop' }, model: PYTHON.model, unchecked: [] })

  expect(result).toEqual({ folder: 'C:/Temp/claude-visual-review/s-1', path: 'C:/Temp/claude-visual-review/s-1/view.json', json: written[0]?.[1] })
  expect(written.map(([path]) => path)).toEqual(['C:/Temp/claude-visual-review/s-1/view.json'])
  expect((JSON.parse(written[0]?.[1] ?? '{}') as ViewModel).files).toEqual([{ path: 'shop/models.py', added: 3, removed: 1, rest: { added: 0, removed: 0 } }])
})
